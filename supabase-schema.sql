-- ============================================================================
-- Game Steps Table
-- Stores step-by-step snapshots of game state for replay functionality
-- ============================================================================

CREATE TABLE IF NOT EXISTS game_steps (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  game_id INTEGER NOT NULL,
  step INTEGER NOT NULL,
  data JSONB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

  -- Ensure unique combination of game_id and step
  CONSTRAINT unique_game_step UNIQUE (game_id, step)
);

-- Index for faster queries by game_id
CREATE INDEX IF NOT EXISTS idx_game_steps_game_id ON game_steps(game_id);

-- Index for faster queries by game_id and step combination
CREATE INDEX IF NOT EXISTS idx_game_steps_game_id_step ON game_steps(game_id, step);

-- Trigger to update updated_at on every update
DROP TRIGGER IF EXISTS update_game_steps_updated_at ON game_steps;
CREATE TRIGGER update_game_steps_updated_at
  BEFORE UPDATE ON game_steps
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

-- Comments for documentation
COMMENT ON TABLE game_steps IS 'Stores step-by-step snapshots of game state for replay functionality';
COMMENT ON COLUMN game_steps.id IS 'Unique identifier (UUID)';
COMMENT ON COLUMN game_steps.game_id IS 'The ID of the game';
COMMENT ON COLUMN game_steps.step IS 'Step number in the game progression (0-indexed, auto-calculated per game_id)';
COMMENT ON COLUMN game_steps.data IS 'Complete game state data from /api/full-game endpoint';
COMMENT ON COLUMN game_steps.created_at IS 'When the step was recorded';
COMMENT ON COLUMN game_steps.updated_at IS 'Last update timestamp';

-- Enable Row Level Security (RLS)
ALTER TABLE game_steps ENABLE ROW LEVEL SECURITY;

-- Policy: Allow anyone to read all game steps
CREATE POLICY "Allow public read access to game steps"
  ON game_steps
  FOR SELECT
  USING (true);

-- Policy: Allow all operations with anon key (for the worker)
CREATE POLICY "Allow all operations on game steps"
  ON game_steps
  FOR ALL
  USING (true)
  WITH CHECK (true);

-- ============================================================================
-- Leaderboard Reward Periods Table
-- Stores completed distribution periods with ranking and rewards data
-- ============================================================================

CREATE TABLE IF NOT EXISTS leaderboard_reward_periods (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  period_type TEXT NOT NULL CHECK (period_type IN ('daily', 'weekly')),
  period_id TEXT NOT NULL, -- YYYY-MM-DD for daily, YYYY-WNN for weekly
  rewards_data JSONB NOT NULL, -- Array of { position, player_address, player_name, level, score, packs: [packId, ...] }
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_period UNIQUE (period_type, period_id)
);

-- Index for faster queries on period_type and period_id
CREATE INDEX IF NOT EXISTS idx_leaderboard_reward_periods_type_id ON leaderboard_reward_periods(period_type, period_id);

-- Comments for documentation
COMMENT ON TABLE leaderboard_reward_periods IS 'Stores completed leaderboard reward distributions with ranking and pack data';
COMMENT ON COLUMN leaderboard_reward_periods.id IS 'Unique identifier (UUID)';
COMMENT ON COLUMN leaderboard_reward_periods.period_type IS 'Type of period: daily or weekly';
COMMENT ON COLUMN leaderboard_reward_periods.period_id IS 'Period identifier: YYYY-MM-DD for daily, YYYY-WNN for weekly';
COMMENT ON COLUMN leaderboard_reward_periods.rewards_data IS 'JSON array with ranking and rewards: [{ position, player_address, player_name, level, score, packs }]';
COMMENT ON COLUMN leaderboard_reward_periods.created_at IS 'When the distribution was recorded';

-- Enable Row Level Security (RLS)
ALTER TABLE leaderboard_reward_periods ENABLE ROW LEVEL SECURITY;

-- Policy: Allow all operations with anon key (for the worker)
CREATE POLICY "Allow all operations on leaderboard reward periods"
  ON leaderboard_reward_periods
  FOR ALL
  USING (true)
  WITH CHECK (true);
