-- Torii Worker Transaction Queue Table (legacy historical queue)
-- This table stores legacy low-level transactions from the Torii worker.
-- New worker writes should use torii_worker_intent_queue below.

CREATE TABLE IF NOT EXISTS torii_worker_transaction_queue (
  id TEXT PRIMARY KEY,
  contract_address TEXT NOT NULL,
  entrypoint TEXT NOT NULL,
  calldata JSONB NOT NULL,
  blockchain TEXT NOT NULL DEFAULT 'starknet' CHECK (blockchain IN ('starknet', 'celo')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
  retries INTEGER NOT NULL DEFAULT 0,
  max_retries INTEGER NOT NULL DEFAULT 3,
  transaction_hash TEXT,
  error_message TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMP WITH TIME ZONE
);

-- Index for faster queries on status
CREATE INDEX IF NOT EXISTS idx_torii_worker_tx_queue_status ON torii_worker_transaction_queue(status);

-- Index for faster queries on created_at (for ordering)
CREATE INDEX IF NOT EXISTS idx_torii_worker_tx_queue_created_at ON torii_worker_transaction_queue(created_at);

-- Index for combined status + created_at queries (most common query pattern)
CREATE INDEX IF NOT EXISTS idx_torii_worker_tx_queue_status_created_at ON torii_worker_transaction_queue(status, created_at);

-- Migration path for existing Starknet-only queues
ALTER TABLE torii_worker_transaction_queue
  ADD COLUMN IF NOT EXISTS blockchain TEXT;

UPDATE torii_worker_transaction_queue
SET
  blockchain = COALESCE(blockchain, 'starknet')
WHERE blockchain IS NULL;

ALTER TABLE torii_worker_transaction_queue
  ALTER COLUMN blockchain SET DEFAULT 'starknet';

ALTER TABLE torii_worker_transaction_queue
  ALTER COLUMN blockchain SET NOT NULL;

-- Optional index for routing by blockchain when operating mixed queues
CREATE INDEX IF NOT EXISTS idx_torii_worker_tx_queue_blockchain_status_created_at
  ON torii_worker_transaction_queue(blockchain, status, created_at);

-- Function to automatically update updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger to update updated_at on every update
DROP TRIGGER IF EXISTS update_torii_worker_tx_queue_updated_at ON torii_worker_transaction_queue;
CREATE TRIGGER update_torii_worker_tx_queue_updated_at
  BEFORE UPDATE ON torii_worker_transaction_queue
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

-- Comments for documentation
COMMENT ON TABLE torii_worker_transaction_queue IS 'Legacy historical queue for low-level Torii worker transactions';
COMMENT ON COLUMN torii_worker_transaction_queue.id IS 'Unique transaction ID generated by the worker';
COMMENT ON COLUMN torii_worker_transaction_queue.contract_address IS 'Target contract address to call';
COMMENT ON COLUMN torii_worker_transaction_queue.entrypoint IS 'Contract function to execute';
COMMENT ON COLUMN torii_worker_transaction_queue.calldata IS 'Function parameters as JSON array';
COMMENT ON COLUMN torii_worker_transaction_queue.blockchain IS 'Legacy target blockchain value for historical low-level jobs';
COMMENT ON COLUMN torii_worker_transaction_queue.status IS 'Current status: pending, processing, completed, or failed';
COMMENT ON COLUMN torii_worker_transaction_queue.retries IS 'Number of retry attempts made';
COMMENT ON COLUMN torii_worker_transaction_queue.max_retries IS 'Maximum retry attempts allowed';
COMMENT ON COLUMN torii_worker_transaction_queue.transaction_hash IS 'Blockchain transaction hash once confirmed';
COMMENT ON COLUMN torii_worker_transaction_queue.error_message IS 'Error message if transaction failed';
COMMENT ON COLUMN torii_worker_transaction_queue.created_at IS 'When the transaction was added to queue';
COMMENT ON COLUMN torii_worker_transaction_queue.updated_at IS 'Last update timestamp';
COMMENT ON COLUMN torii_worker_transaction_queue.completed_at IS 'When the transaction was completed or failed permanently';

-- Enable Row Level Security (RLS)
ALTER TABLE torii_worker_transaction_queue ENABLE ROW LEVEL SECURITY;

-- Create policies to allow all operations with anon key
-- IMPORTANT: This allows full access. In production, you might want more restrictive policies.
CREATE POLICY "Allow all operations on transaction queue"
ON torii_worker_transaction_queue
FOR ALL
USING (true)
WITH CHECK (true);

-- ============================================================================
-- Torii Worker Intent Queue Table
-- Stores chain-agnostic transaction intents. Blockchain support is validated by
-- the worker adapter registry instead of a database allowlist.
-- ============================================================================

CREATE TABLE IF NOT EXISTS torii_worker_intent_queue (
  id TEXT PRIMARY KEY,
  blockchain TEXT NOT NULL,
  operation TEXT NOT NULL,
  target_ref TEXT,
  payload JSONB NOT NULL,
  intent_version INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
  retries INTEGER NOT NULL DEFAULT 0,
  max_retries INTEGER NOT NULL DEFAULT 3,
  transaction_hash TEXT,
  error_message TEXT,
  metadata JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_torii_worker_intent_queue_status ON torii_worker_intent_queue(status);
CREATE INDEX IF NOT EXISTS idx_torii_worker_intent_queue_created_at ON torii_worker_intent_queue(created_at);
CREATE INDEX IF NOT EXISTS idx_torii_worker_intent_queue_status_created_at ON torii_worker_intent_queue(status, created_at);
CREATE INDEX IF NOT EXISTS idx_torii_worker_intent_queue_blockchain_status_created_at ON torii_worker_intent_queue(blockchain, status, created_at);
CREATE INDEX IF NOT EXISTS idx_torii_worker_intent_queue_operation_status ON torii_worker_intent_queue(operation, status);

DROP TRIGGER IF EXISTS update_torii_worker_intent_queue_updated_at ON torii_worker_intent_queue;
CREATE TRIGGER update_torii_worker_intent_queue_updated_at
  BEFORE UPDATE ON torii_worker_intent_queue
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE torii_worker_intent_queue IS 'Persistent queue for worker transaction intents. Chain support is validated by the worker adapter registry.';
