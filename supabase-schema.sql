COMMENT ON COLUMN torii_worker_intent_queue.blockchain IS 'Target blockchain adapter id, for example starknet or celo. No DB allowlist is enforced.';
COMMENT ON COLUMN torii_worker_intent_queue.operation IS 'Semantic operation to execute, for example game.snapshot or progression.sync';
