-- ============================================================================
-- Player Streak Cache Tables
-- Cache daily streak state for fast reads, optimistic pending UI, and future
-- streak leaderboards. On-chain Profile remains the source of truth.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS player_streaks (
  player_address TEXT PRIMARY KEY,
  username TEXT,
  current_streak INTEGER NOT NULL DEFAULT 0 CHECK (current_streak >= 0),
  effective_streak INTEGER NOT NULL DEFAULT 0 CHECK (effective_streak >= 0),
  longest_streak INTEGER NOT NULL DEFAULT 0 CHECK (longest_streak >= 0),
  last_completed_day BIGINT NOT NULL DEFAULT 0,
  protectors_available INTEGER NOT NULL DEFAULT 0 CHECK (protectors_available >= 0),
  protectors_needed BIGINT NOT NULL DEFAULT 0 CHECK (protectors_needed >= 0),
  days_missed BIGINT NOT NULL DEFAULT 0 CHECK (days_missed >= 0),
  is_protected BOOLEAN NOT NULL DEFAULT FALSE,
  is_broken BOOLEAN NOT NULL DEFAULT FALSE,
  sync_status TEXT NOT NULL DEFAULT 'confirmed' CHECK (sync_status IN ('confirmed', 'pending', 'failed')),
  pending_period_id BIGINT,
  pending_mission_id TEXT,
  pending_template_id TEXT,
  last_tx_hash TEXT,
  last_synced_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_player_streaks_effective_streak
  ON player_streaks(effective_streak DESC, longest_streak DESC, last_completed_day DESC);

CREATE INDEX IF NOT EXISTS idx_player_streaks_sync_status
  ON player_streaks(sync_status);

CREATE INDEX IF NOT EXISTS idx_player_streaks_pending_period
  ON player_streaks(pending_period_id)
  WHERE pending_period_id IS NOT NULL;

DROP TRIGGER IF EXISTS update_player_streaks_updated_at ON player_streaks;
CREATE TRIGGER update_player_streaks_updated_at
  BEFORE UPDATE ON player_streaks
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE player_streaks IS 'Cached player daily streak state for fast reads and leaderboards';
COMMENT ON COLUMN player_streaks.player_address IS 'Normalized Starknet player address';
COMMENT ON COLUMN player_streaks.current_streak IS 'Last known on-chain streak count';
COMMENT ON COLUMN player_streaks.effective_streak IS 'Streak count adjusted for missed days and available protectors';
COMMENT ON COLUMN player_streaks.sync_status IS 'Whether the cached daily mission completion is pending, confirmed, or failed on-chain';

ALTER TABLE player_streaks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access to player streaks" ON player_streaks;
CREATE POLICY "Allow public read access to player streaks"
  ON player_streaks
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Allow all operations on player streaks" ON player_streaks;
CREATE POLICY "Allow all operations on player streaks"
  ON player_streaks
  FOR ALL
  USING (true)
  WITH CHECK (true);

